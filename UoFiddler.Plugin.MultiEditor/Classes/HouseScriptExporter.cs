/***************************************************************************
 *
 * MultiEditor – ServUO house script (BaseHouse + HouseDeed) with doors,
 * sign and ban location placed in the editor.
 *
 ***************************************************************************/

using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace UoFiddler.Plugin.MultiEditor.Classes
{
    public enum HouseMarkerKind
    {
        DoorSouth = 1,
        DoorEast = 2,
        Sign = 3,
        BanLocation = 4
    }

    /// <summary>
    /// Marker in cell coordinates of the editor
    /// </summary>
    public sealed class HouseMarker
    {
        public HouseMarkerKind Kind { get; set; }
        public int X { get; set; }
        public int Y { get; set; }
        public int Z { get; set; }

        public string Letter => Kind switch
        {
            HouseMarkerKind.DoorSouth => "TS",
            HouseMarkerKind.DoorEast => "TO",
            HouseMarkerKind.Sign => "S",
            _ => "B"
        };

        public string Name => Kind switch
        {
            HouseMarkerKind.DoorSouth => L.T("Tür (Süd)", "Door (south)"),
            HouseMarkerKind.DoorEast => L.T("Tür (Ost)", "Door (east)"),
            HouseMarkerKind.Sign => L.T("Hausschild", "House sign"),
            _ => L.T("Ban-Location", "Ban location")
        };
    }

    public sealed class HouseScriptOptions
    {
        public string Name { get; set; } = "MyHouse";
        public string DeedName { get; set; } = "a house deed";
        /// <summary>
        /// Both classes go into this namespace. Server.Multis.Deeds works for RunUO and ServUO
        /// (HouseDeed lives in Server.Multis or Server.Multis.Deeds, both are found from here).
        /// </summary>
        public string Namespace { get; set; } = "Server.Multis.Deeds";
        public int MultiId { get; set; }
        public int Price { get; set; } = 50000;
        public int MaxLockDowns { get; set; } = 425;
        public int MaxSecures { get; set; } = 3;
        public bool WoodDoors { get; set; } = true;
    }

    public static class HouseScriptExporter
    {
        /// <summary>
        /// Creates BaseHouse + HouseDeed. Tiles and markers are relative to the multi center (origin).
        /// </summary>
        public static string Create(IList<ImportTile> tiles, IList<HouseMarker> markers, HouseScriptOptions o)
        {
            string cls = MultiFormats.SanitizeClassName(o.Name);
            if (!cls.EndsWith("House", StringComparison.Ordinal))
            {
                cls += "House";
            }

            List<ImportTile> footprint = tiles.Where(t => !t.Deco && t.Id != 0x1).ToList();
            int minX = footprint.Count > 0 ? footprint.Min(t => t.X) : 0;
            int minY = footprint.Count > 0 ? footprint.Min(t => t.Y) : 0;
            int maxX = footprint.Count > 0 ? footprint.Max(t => t.X) : 0;
            int maxY = footprint.Count > 0 ? footprint.Max(t => t.Y) : 0;

            HouseMarker ban = markers.FirstOrDefault(m => m.Kind == HouseMarkerKind.BanLocation);
            string banLoc = ban != null ? $"{ban.X}, {ban.Y}, {ban.Z}" : $"{minX}, {maxY + 1}, 0";
            string deedOffset = $"0, {maxY + 1}, 0";

            string I(int v) => v.ToString(CultureInfo.InvariantCulture);
            string Esc(string s) => (s ?? string.Empty).Replace("\\", "\\\\").Replace("\"", "\\\"");

            var sb = new StringBuilder();
            sb.AppendLine("// ------------------------------------------------------------------");
            sb.AppendLine($"// {cls}  -  generated by UO Fiddler MultiEditor  {DateTime.Now:yyyy-MM-dd HH:mm}");
            sb.AppendLine($"// Multi id 0x{o.MultiId:X4} - the multi must exist in the multi.mul / MultiCollection.uop of server and client.");
            sb.AppendLine("// ------------------------------------------------------------------");
            sb.AppendLine("using System;");
            sb.AppendLine("using Server;");
            sb.AppendLine("using Server.Items;");
            sb.AppendLine("using Server.Multis;");
            sb.AppendLine();
            sb.AppendLine($"namespace {o.Namespace}");
            sb.AppendLine("{");
            sb.AppendLine($"    public class {cls} : BaseHouse");
            sb.AppendLine("    {");
            sb.AppendLine("        public static Rectangle2D[] AreaArray = new Rectangle2D[]");
            sb.AppendLine("        {");
            sb.AppendLine($"            new Rectangle2D({I(minX)}, {I(minY)}, {I(maxX - minX + 1)}, {I(maxY - minY + 1)})");
            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine($"        public override int DefaultPrice => {I(o.Price)};");
            sb.AppendLine("        public override Rectangle2D[] Area => AreaArray;");
            sb.AppendLine($"        public override Point3D BaseBanLocation => new Point3D({banLoc});");
            sb.AppendLine();
            sb.AppendLine($"        public {cls}(Mobile owner)");
            sb.AppendLine($"            : base(0x{o.MultiId:X4}, owner, {I(o.MaxLockDowns)}, {I(o.MaxSecures)})");
            sb.AppendLine("        {");

            List<HouseMarker> doors = markers.Where(m => m.Kind is HouseMarkerKind.DoorSouth or HouseMarkerKind.DoorEast).ToList();
            if (doors.Count > 0)
            {
                sb.AppendLine("            uint keyValue = CreateKeys(owner);");
                sb.AppendLine();
                foreach (HouseMarker d in doors)
                {
                    string method = d.Kind == HouseMarkerKind.DoorSouth ? "AddSouthDoor" : "AddEastDoor";
                    sb.AppendLine($"            {method}({(o.WoodDoors ? "true" : "false")}, {I(d.X)}, {I(d.Y)}, {I(d.Z)}, keyValue);");
                }

                sb.AppendLine();
            }

            HouseMarker sign = markers.FirstOrDefault(m => m.Kind == HouseMarkerKind.Sign);
            sb.AppendLine(sign != null
                ? $"            SetSign({I(sign.X)}, {I(sign.Y)}, {I(sign.Z)});"
                : $"            SetSign({I(minX)}, {I(maxY + 1)}, 5);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        public {cls}(Serial serial)");
            sb.AppendLine("            : base(serial)");
            sb.AppendLine("        {");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        public override HouseDeed GetDeed() => new {cls}Deed();");
            sb.AppendLine();
            sb.AppendLine("        public override void Serialize(GenericWriter writer)");
            sb.AppendLine("        {");
            sb.AppendLine("            base.Serialize(writer);");
            sb.AppendLine("            writer.Write(0); // version");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public override void Deserialize(GenericReader reader)");
            sb.AppendLine("        {");
            sb.AppendLine("            base.Deserialize(reader);");
            sb.AppendLine("            reader.ReadInt();");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine($"    public class {cls}Deed : HouseDeed");
            sb.AppendLine("    {");
            sb.AppendLine("        [Constructable]");
            sb.AppendLine($"        public {cls}Deed()");
            sb.AppendLine($"            : base(0x{o.MultiId:X4}, new Point3D({deedOffset}))");
            sb.AppendLine("        {");
            sb.AppendLine($"            Name = \"{Esc(o.DeedName)}\";");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        public {cls}Deed(Serial serial)");
            sb.AppendLine("            : base(serial)");
            sb.AppendLine("        {");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        public override Rectangle2D[] Area => {cls}.AreaArray;");
            sb.AppendLine();
            sb.AppendLine($"        public override BaseHouse GetHouse(Mobile owner) => new {cls}(owner);");
            sb.AppendLine();
            sb.AppendLine("        public override void Serialize(GenericWriter writer)");
            sb.AppendLine("        {");
            sb.AppendLine("            base.Serialize(writer);");
            sb.AppendLine("            writer.Write(0); // version");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public override void Deserialize(GenericReader reader)");
            sb.AppendLine("        {");
            sb.AppendLine("            base.Deserialize(reader);");
            sb.AppendLine("            reader.ReadInt();");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }
    }
}
